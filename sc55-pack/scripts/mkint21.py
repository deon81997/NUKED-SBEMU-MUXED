#!/usr/bin/env python3
"""Assemble sbemu/int21.asm with NASM and write sbemu/int21bin.h (the INT 21h EXEC stub's bytes for main.c)."""
import subprocess, sys, os, tempfile
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'sbemu', 'int21.asm')
dst = os.path.join(here, '..', 'sbemu', 'int21bin.h')
with tempfile.TemporaryDirectory() as t:
    out = os.path.join(t, 'int21.bin')
    subprocess.check_call(['nasm', '-f', 'bin', src, '-o', out])
    b = open(out, 'rb').read()
lines = ['/* generated by scripts/mkint21.py from sbemu/int21.asm - do not edit */',
         '#define MAIN_I21_ENTRY 0xC0', '#define MAIN_I21_PATH 16', '#define MAIN_I21_NAME 174',
         'static const unsigned char MAIN_I21Stub[%d] = {' % len(b)]
for i in range(0, len(b), 20):
    lines.append('    ' + ' '.join('0x%02X,' % x for x in b[i:i + 20]))
lines.append('};')
open(dst, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d bytes' % (dst, len(b)))
