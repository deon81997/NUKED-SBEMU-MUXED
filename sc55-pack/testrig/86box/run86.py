# run86.py VMDIR OUTDIR: SBEMU + MIDPLAY (text, panel, 3D: 3 looks x 4 players x themes) + MENU (text, 3D styles)
import sys, os, time
sys.path.insert(0, '/home/claude/nuked-sbemu-muxed/sc55-pack/testrig/86box')
from regress import VM, Report, colours, ESC, F3, F8
vmd, out = sys.argv[1], sys.argv[2]; os.makedirs(out, exist_ok=True)
vm = VM(vmd, out); R = Report(out); tag = os.path.basename(vmd)
vm.rm('CRASH.TXT')
vm.boot()
vm.run('sbemu', 12000); s = vm.screen()
R.check(tag + ' SBEMU loads', 'Protected mode support: enabled' in s and 'MPU-401' in s)
vm.run('midplay t.mid', 9000); s = vm.screen(); vm.shot(tag + '_mp_text')
R.check(tag + ' MIDPLAY text view', 'MIDPLAY' in s.upper(), s.splitlines()[0][:60] if s else '')
vm.key(0x1f, 5000); vm.shot(tag + '_mp_panel'); s = vm.screen()
R.check(tag + ' MIDPLAY panel view', bool(s.strip()) or colours(vm.shot(tag + '_mp_panel2')) > 8)
t0 = time.time(); vm.key(0x1f, 10000); p = vm.shot(tag + '_mp_3d')
R.check(tag + ' MIDPLAY 3D view', colours(p) > 100, '%d colours' % colours(p))
for i in range(3):
    vm.key(0x2f, 6000); p = vm.shot('%s_mp_look%d' % (tag, i))
    R.check('%s MIDPLAY look %d' % (tag, i), colours(p) > 30, '%d colours' % colours(p))
    for j in range(4):
        vm.key(0x24, 4000); p = vm.shot('%s_mp_look%d_player%d' % (tag, i, j))
        R.check('%s MIDPLAY look %d player %d' % (tag, i, j), colours(p) > 30, '%d colours' % colours(p))
    vm.key(0x2e, 3000)
for k in range(8): vm.key(0x2e, 2500)
p = vm.shot(tag + '_mp_themes'); R.check(tag + ' MIDPLAY themes cycled', colours(p) > 30, '%d colours' % colours(p))
vm.key(ESC, 1500); vm.key(ESC, 4000); s = vm.screen()
R.check(tag + ' MIDPLAY quits', 'C:\\>' in s, s.splitlines()[-1][:60] if s else '')
vm.run('sc55menu c:\\', 7000); s = vm.screen(); vm.shot(tag + '_menu_text')
R.check(tag + ' MENU text', 'SBEMU' in s or 'Sound' in s)
vm.key(ESC, 1500)
vm.key(F8, 7000); p = vm.shot(tag + '_menu_3d0'); R.check(tag + ' MENU 3D', colours(p) > 100, '%d colours' % colours(p))
for i in range(1, 6):
    vm.key(F3, 5000); vm.key(0x4d, 1500); p = vm.shot('%s_menu_3d%d' % (tag, i))
    R.check('%s MENU 3D style %d' % (tag, i), colours(p) > 100, '%d colours' % colours(p))
vm.key(F8, 4000); s = vm.screen(); R.check(tag + ' MENU back to text', 'Tests' in s)
vm.key(ESC, 3000); s = vm.screen()
vm.stop()
c = vm.get('CRASH.TXT'); R.check(tag + ' no CRASH.TXT', not c, c[:200])
R.save(); print(open(os.path.join(out, 'regress.txt')).read() if os.path.exists(os.path.join(out, 'regress.txt')) else '')
